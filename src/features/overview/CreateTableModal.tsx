import { Plus, Table, Trash2, X } from 'lucide-react';
import type React from 'react';
import { useEffect, useMemo, useState } from 'react';
import { Checkbox } from '../../components/ui/Checkbox';
import { createTable } from '../../services/tauri';
import type { ColumnDefinition, ConnectionSummary, SchemaInfo } from '../../types/database';

interface CreateTableModalProps {
  isOpen: boolean;
  connection: ConnectionSummary;
  schemas: SchemaInfo[];
  onClose: () => void;
  onTableCreated: () => void;
  onShowToast: (msg: string, type?: 'success' | 'error' | 'info') => void;
}

type ColumnDraft = ColumnDefinition & { _key: string };

const DEFAULT_COLUMNS: ColumnDefinition[] = [
  {
    name: 'id',
    dataType: 'INTEGER',
    nullable: false,
    primaryKey: true,
    defaultValue: '',
    autoIncrement: true,
  },
  {
    name: 'created_at',
    dataType: 'TIMESTAMPTZ',
    nullable: false,
    primaryKey: false,
    defaultValue: 'CURRENT_TIMESTAMP',
    autoIncrement: false,
  },
];

export const CreateTableModal: React.FC<CreateTableModalProps> = ({
  isOpen,
  connection,
  schemas,
  onClose,
  onTableCreated,
  onShowToast,
}) => {
  const eng = connection.engineKind;
  const isPg = eng === 'postgres';
  const isMysql = eng === 'mysql';
  const hasSchemas = isPg || isMysql;
  const availableSchemas = useMemo(
    () => schemas.filter((s) => !s.isSystem).map((s) => s.name),
    [schemas],
  );
  const defaultSchema = availableSchemas[0] || (isPg ? 'public' : 'main');
  const [schema, setSchema] = useState(hasSchemas ? defaultSchema : 'main');
  const [tableName, setTableName] = useState('');
  const [columns, setColumns] = useState<ColumnDraft[]>(() =>
    DEFAULT_COLUMNS.map((c, idx) => ({ ...c, _key: `init_${idx}` })),
  );
  const [creating, setCreating] = useState(false);

  useEffect(() => {
    if (!isOpen) return;
    setSchema(hasSchemas ? defaultSchema : 'main');
    setTableName('');
    setColumns(
      DEFAULT_COLUMNS.map((c, idx) => ({
        ...c,
        _key: `col_${Date.now()}_${idx}`,
        dataType:
          c.name === 'id'
            ? isPg || isMysql
              ? 'BIGINT'
              : 'INTEGER'
            : isPg
              ? 'TIMESTAMPTZ'
              : isMysql
                ? 'TIMESTAMP'
                : 'TEXT',
      })),
    );
  }, [isOpen, hasSchemas, isPg, isMysql, defaultSchema]);

  const previewSql = useMemo(() => {
    const q = (ident: string) => (isMysql ? `\`${ident}\`` : `"${ident}"`);
    const tbl = tableName.trim() || 'new_table';
    const qual = hasSchemas && schema ? `${q(schema)}.${q(tbl)}` : q(tbl);
    const pks: string[] = [];
    const lines = columns.map((c) => {
      const cname = q(c.name || 'col');
      let line = `  ${cname} ${c.dataType}`;
      if (isPg && c.autoIncrement) {
        line += ' GENERATED BY DEFAULT AS IDENTITY';
      } else if (isMysql && c.autoIncrement) {
        line += ' AUTO_INCREMENT';
      }
      if (!c.nullable) line += ' NOT NULL';
      if (!c.autoIncrement && c.defaultValue?.trim()) {
        line += ` DEFAULT ${c.defaultValue.trim()}`;
      }
      if (c.primaryKey) {
        if (eng === 'sqlite' && c.autoIncrement && c.dataType.toUpperCase() === 'INTEGER') {
          line += ' PRIMARY KEY AUTOINCREMENT';
        } else {
          pks.push(cname);
        }
      }
      return line;
    });
    if (pks.length > 0) {
      lines.push(`  PRIMARY KEY (${pks.join(', ')})`);
    }
    return `CREATE TABLE ${qual} (\n${lines.join(',\n')}\n);`;
  }, [tableName, schema, columns, eng, hasSchemas, isPg, isMysql]);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!tableName.trim() || columns.length === 0) return;
    setCreating(true);
    try {
      await createTable({
        connectionId: connection.id,
        name: tableName.trim(),
        schema: hasSchemas ? schema : undefined,
        columns: columns.map(({ _key, ...c }) => ({
          ...c,
          defaultValue: c.defaultValue?.trim() || undefined,
        })),
      });
      onShowToast(`Table "${tableName.trim()}" created`, 'success');
      onTableCreated();
      onClose();
    } catch (err) {
      onShowToast(`Create table failed: ${err}`, 'error');
    } finally {
      setCreating(false);
    }
  };

  const typeOptions = isPg
    ? [
        'BIGINT',
        'INTEGER',
        'TEXT',
        'VARCHAR(255)',
        'BOOLEAN',
        'NUMERIC(12,2)',
        'UUID',
        'JSONB',
        'TIMESTAMPTZ',
        'DATE',
        'BYTEA',
      ]
    : isMysql
      ? [
          'BIGINT',
          'INT',
          'VARCHAR(255)',
          'TEXT',
          'BOOLEAN',
          'DECIMAL(12,2)',
          'JSON',
          'DATETIME',
          'TIMESTAMP',
          'DATE',
          'BLOB',
        ]
      : ['INTEGER', 'TEXT', 'REAL', 'BLOB', 'NUMERIC', 'BOOLEAN'];

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/55 backdrop-blur-[2px] p-4"
      onClick={onClose}
    >
      <form
        onSubmit={handleSubmit}
        onClick={(e) => e.stopPropagation()}
        className="w-full max-w-3xl bg-[var(--bg-panel)] border border-[var(--border)] rounded-xl shadow-2xl overflow-hidden flex flex-col max-h-[88vh] animate-in"
      >
        <div className="px-5 py-3.5 border-b border-[var(--border)] bg-[var(--bg-surface)] flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Table size={15} className="text-[var(--accent)]" />
            <h3 className="text-sm font-semibold text-[var(--text)]">Create New Table</h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close Create Table Modal"
            title="Close (Esc)"
            className="p-1 rounded hover:bg-[var(--bg-hover)] text-[var(--text-muted)]"
          >
            <X size={14} />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto p-5 space-y-4 text-xs">
          <div className="grid grid-cols-12 gap-3">
            {hasSchemas && (
              <div className="col-span-4">
                <label className="block text-[11px] text-[var(--text-muted)] mb-1">Schema</label>
                <select
                  value={schema}
                  onChange={(e) => setSchema(e.target.value)}
                  className="w-full font-mono"
                >
                  {(availableSchemas.length > 0 ? availableSchemas : [defaultSchema]).map((s) => (
                    <option key={s} value={s}>
                      {s}
                    </option>
                  ))}
                </select>
              </div>
            )}
            <div className={hasSchemas ? 'col-span-8' : 'col-span-12'}>
              <label className="block text-[11px] text-[var(--text-muted)] mb-1">Table Name</label>
              <input
                type="text"
                value={tableName}
                onChange={(e) => setTableName(e.target.value)}
                placeholder="e.g. customers"
                className="w-full font-mono"
                required
                autoFocus
              />
            </div>
          </div>

          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="font-semibold text-[var(--text-secondary)]">Columns</span>
              <button
                type="button"
                onClick={() =>
                  setColumns((prev) => [
                    ...prev,
                    {
                      _key: `col_${Date.now()}_${prev.length}`,
                      name: `col_${prev.length + 1}`,
                      dataType: 'TEXT',
                      nullable: true,
                      primaryKey: false,
                      defaultValue: '',
                      autoIncrement: false,
                    },
                  ])
                }
                className="px-2 py-1 rounded border border-[var(--border)] bg-[var(--bg-surface)] hover:bg-[var(--bg-hover)] inline-flex items-center gap-1"
              >
                <Plus size={11} /> Add Column
              </button>
            </div>

            <div className="space-y-2">
              {columns.map((col, idx) => (
                <div
                  key={col._key}
                  className="p-2.5 rounded-lg bg-[var(--bg-surface)] border border-[var(--border)] grid grid-cols-12 gap-2 items-center"
                >
                  <input
                    type="text"
                    value={col.name}
                    onChange={(e) =>
                      setColumns((p) =>
                        p.map((c, i) => (i === idx ? { ...c, name: e.target.value } : c)),
                      )
                    }
                    placeholder="column_name"
                    className="col-span-3 font-mono"
                    required
                  />
                  <select
                    value={col.dataType}
                    onChange={(e) =>
                      setColumns((p) =>
                        p.map((c, i) => (i === idx ? { ...c, dataType: e.target.value } : c)),
                      )
                    }
                    className="col-span-3 font-mono"
                  >
                    {typeOptions.map((t) => (
                      <option key={t} value={t}>
                        {t}
                      </option>
                    ))}
                  </select>
                  <input
                    type="text"
                    value={col.defaultValue || ''}
                    onChange={(e) =>
                      setColumns((p) =>
                        p.map((c, i) => (i === idx ? { ...c, defaultValue: e.target.value } : c)),
                      )
                    }
                    placeholder="Default"
                    className="col-span-2 font-mono"
                  />
                  <div className="col-span-3 flex items-center gap-2.5">
                    <Checkbox
                      checked={col.primaryKey}
                      onChange={(v) =>
                        setColumns((p) =>
                          p.map((c, i) => (i === idx ? { ...c, primaryKey: v } : c)),
                        )
                      }
                      size="sm"
                      label="PK"
                    />
                    <Checkbox
                      checked={!col.nullable}
                      onChange={(v) =>
                        setColumns((p) => p.map((c, i) => (i === idx ? { ...c, nullable: !v } : c)))
                      }
                      size="sm"
                      label="NN"
                    />
                    <Checkbox
                      checked={col.autoIncrement}
                      onChange={(v) =>
                        setColumns((p) =>
                          p.map((c, i) => (i === idx ? { ...c, autoIncrement: v } : c)),
                        )
                      }
                      size="sm"
                      label="AI"
                    />
                  </div>
                  <div className="col-span-1 flex justify-end">
                    <button
                      type="button"
                      disabled={columns.length <= 1}
                      onClick={() => setColumns((p) => p.filter((_, i) => i !== idx))}
                      className="p-1 rounded hover:bg-[var(--error)]/15 text-[var(--text-muted)] hover:text-[var(--error)] disabled:opacity-30"
                    >
                      <Trash2 size={12} />
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>

          <div>
            <div className="text-[11px] font-semibold text-[var(--text-muted)] uppercase tracking-wider mb-1">
              SQL Preview ({connection.engine})
            </div>
            <pre className="p-3 rounded-lg bg-[var(--code-bg)] border border-[var(--border)] font-mono text-[11px] text-[var(--text)] overflow-x-auto">
              {previewSql}
            </pre>
          </div>
        </div>

        <div className="px-5 py-3 border-t border-[var(--border)] bg-[var(--bg-surface)] flex justify-end gap-2 text-xs">
          <button
            type="button"
            onClick={onClose}
            className="px-3 py-1.5 rounded-md border border-[var(--border)] bg-[var(--bg-panel)]"
          >
            Cancel
          </button>
          <button
            type="submit"
            disabled={creating || !tableName.trim()}
            className="px-4 py-1.5 rounded-md bg-[var(--accent)] text-[var(--accent-text)] font-semibold hover:bg-[var(--accent-hover)] disabled:opacity-50"
          >
            {creating ? 'Creating…' : 'Create Table'}
          </button>
        </div>
      </form>
    </div>
  );
};
