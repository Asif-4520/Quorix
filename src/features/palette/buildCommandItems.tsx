  isSqlActive: boolean;
  onOpenConnections: () => void;
  onDisconnect: () => void;
  onNewSqlTab: () => void;
  onExecuteQuery: () => void;
  onExecuteAll?: () => void;
  onExplainQuery?: () => void;
